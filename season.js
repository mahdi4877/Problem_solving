let month = 7;

switch (month) {
  case 1:
  case 2:
    console.log("Winter");
    break;

  case 3:
  case 4:
    console.log("Spring");
    break;

  case 5:
  case 6:
    console.log("Summer");
    break;

  case 7:
  case 8:
    console.log("Monsoon");
    break;

  case 9:
  case 10:
    console.log("Autumn");
    break;

  case 11:
  case 12:
    console.log("Late Autumn");
    break;

  default:
    console.log("Invalid month");
}
